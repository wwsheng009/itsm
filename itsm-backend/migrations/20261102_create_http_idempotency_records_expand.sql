-- 20261102 创建 HTTP Idempotency-Key 记录表（expand 阶段，幂等可重跑）。
-- 契约：客户端对非安全方法携带 Idempotency-Key；服务端按
-- (tenant_id, user_id, method, path, idempotency_key) 唯一去重，成功响应缓存 24h。
-- 只缓存 2xx；4xx/5xx 与超大响应会删除 processing 行，允许客户端修复后重试。

BEGIN;

CREATE TABLE IF NOT EXISTS http_idempotency_records (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id              BIGINT       NOT NULL,
    user_id                BIGINT       NOT NULL,
    method                 VARCHAR(10)  NOT NULL,
    path                   VARCHAR(512) NOT NULL,
    idempotency_key        VARCHAR(128) NOT NULL,
    request_hash           VARCHAR(64)  NOT NULL,
    state                  VARCHAR(16)  NOT NULL DEFAULT 'processing',
    status_code            INTEGER      NOT NULL DEFAULT 0,
    response_body          TEXT,
    response_content_type  VARCHAR(255),
    created_at             TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    completed_at           TIMESTAMPTZ,
    expires_at             TIMESTAMPTZ  NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_http_idempotency_scope
    ON http_idempotency_records (tenant_id, user_id, method, path, idempotency_key);

CREATE INDEX IF NOT EXISTS idx_http_idempotency_expires
    ON http_idempotency_records (expires_at);

COMMIT;
