-- 20260923 回填 attachments：把 ticket_attachments 历史行平移到通用附件表（P2/DO-1）。
-- 方案：docs/plan/generic-attachment-richtext-control-plan.md §5.2（v1.0 冻结回填 SQL）。
--
-- 为什么版本号是 20260923 而不是 20260922：迁移流按 version 字符串升序执行，
-- 「20260922_attachments_backfill...」会排在「20260922_create_attachments_expand」之前
-- （a < c），导致表尚未创建就回填。放到次日保证 expand → backfill 顺序确定。
--
-- 不变式（三条，缺一不可）：
--   1) 保 ID 平移：id 原样复制。历史富文本 HTML 的 data-attachment-id 与
--      /tickets/:id/attachments/:ref URL 都引用旧 ID，改号即裂图（§5.2 硬要求）。
--   2) 幂等可重跑：ON CONFLICT (id) DO NOTHING，已存在的行（含新链路新写的）不被覆盖。
--   3) 序列对齐：回填写的是显式 id，不推进 IDENTITY 序列；不 setval 则后续新上传
--      会从 1 开始撞主键。pg_get_serial_sequence 对 IDENTITY 列同样有效
--      （GENERATED BY DEFAULT AS IDENTITY 背后是 owned sequence）。
--
-- 容错：attachments / ticket_attachments 任一缺失（全新库、或 P5 后旧表已 drop）时
-- 整段跳过并留 NOTICE，不阻断迁移流。历史表无 status/deleted_at/sha256/client_token，
-- 故回填列取 §5.2 的字段映射，status 固定 'active'、client_token 留 NULL。

DO $$
DECLARE
    copied   BIGINT  := 0;
    max_id   BIGINT  := 0;
    has_rows BOOLEAN := FALSE;
BEGIN
    IF to_regclass('public.attachments') IS NULL THEN
        RAISE NOTICE 'attachments 表不存在，跳过回填（应先执行 20260922_create_attachments_expand）';
        RETURN;
    END IF;
    IF to_regclass('public.ticket_attachments') IS NULL THEN
        RAISE NOTICE 'ticket_attachments 不存在（全新库或已下线），跳过回填';
        RETURN;
    END IF;

    INSERT INTO attachments
        (id, tenant_id, biz_type, biz_id, usage, file_name, file_path, file_url,
         file_size, file_type, mime_type, uploaded_by, status, created_at)
    SELECT t.id, t.tenant_id, 'ticket', t.ticket_id, 'attachment',
           t.file_name, t.file_path, t.file_url,
           t.file_size, t.file_type, t.mime_type, t.uploaded_by, 'active', t.created_at
    FROM ticket_attachments t
    ON CONFLICT (id) DO NOTHING;

    GET DIAGNOSTICS copied = ROW_COUNT;

    SELECT COALESCE(MAX(id), 0) INTO max_id FROM attachments;
    SELECT EXISTS (SELECT 1 FROM attachments) INTO has_rows;

    -- 空表时 is_called=false → 下一个 nextval 就是 1，不留空洞。
    PERFORM setval(pg_get_serial_sequence('attachments', 'id'),
                   GREATEST(max_id, 1),
                   has_rows);

    RAISE NOTICE 'attachments 回填完成：本次复制 % 行，MAX(id)=%，IDENTITY 序列已对齐（has_rows=%）',
        copied, max_id, has_rows;
END $$;
