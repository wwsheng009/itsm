-- =============================================================================
-- P2 · MSP 多租户帮助空间与分发授权（方案 §P2 智能化与运营 / Q2 客户上下文同批）
--
-- 1) msp_help_docs：provider 侧「帮助空间」文档（owner = provider 租户）。
--    - slug 在 provider 内唯一；draft → publish 门禁，仅 published 可分发；
--    - 编辑已发布文档会回到 draft 并推进版本（v+1），需重新发布（对齐模板分发的"仅已发布可分发"）。
-- 2) msp_help_distributions：provider → 客户租户的 copy-in 快照 + 来源追踪
--    （owner = 客户租户，tenant_id 供租户守卫/RLS 识别；provider_tenant_id 为来源）。
--    语义对齐 workflow_template_distributions / ticket_type_distributions 先例：
--    "副本就是普通 customer 租户行"，provider 侧访问经 mspguard（allocation + 客户 active）
--    授权后以客户租户作用域重绑定 ctx（零跨租户读，§4.5a）。
--    - active 行唯一（tenant_id + source_slug）；upgrade 原位刷新快照到最新已发布版本；
--    - unbind 后副本转为客户原生内容（保留可见，不再追踪 provider 更新）。
--
-- RLS：database/rls/migrations/016_msp_help_policies.sql（两表 tenant 隔离，只 ENABLE 不 FORCE）。
-- =============================================================================

CREATE TABLE IF NOT EXISTS msp_help_docs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id    INTEGER      NOT NULL,
    slug         VARCHAR(64)  NOT NULL,
    title        VARCHAR(255) NOT NULL,
    page_key     VARCHAR(128) NOT NULL DEFAULT '',
    body_md      TEXT         NOT NULL DEFAULT '',
    status       VARCHAR(16)  NOT NULL DEFAULT 'draft',
    version      INTEGER      NOT NULL DEFAULT 1,
    created_by   INTEGER      NOT NULL DEFAULT 0,
    updated_by   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    published_at TIMESTAMPTZ  NULL,
    UNIQUE (tenant_id, slug)
);

CREATE INDEX IF NOT EXISTS idx_msp_help_docs_tenant_status
    ON msp_help_docs (tenant_id, status);

CREATE TABLE IF NOT EXISTS msp_help_distributions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          INTEGER      NOT NULL,
    provider_tenant_id INTEGER      NOT NULL,
    source_doc_id      BIGINT       NOT NULL,
    source_slug        VARCHAR(64)  NOT NULL,
    source_version     INTEGER      NOT NULL,
    source_updated_at  TIMESTAMPTZ  NOT NULL,
    title              VARCHAR(255) NOT NULL,
    page_key           VARCHAR(128) NOT NULL DEFAULT '',
    body_md            TEXT         NOT NULL DEFAULT '',
    status             VARCHAR(16)  NOT NULL DEFAULT 'active',
    distributed_by     INTEGER      NOT NULL DEFAULT 0,
    distributed_at     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    unbound_by         INTEGER      NOT NULL DEFAULT 0,
    unbound_at         TIMESTAMPTZ  NULL,
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_msp_help_distributions_active
    ON msp_help_distributions (tenant_id, source_slug) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS idx_msp_help_distributions_tenant_provider
    ON msp_help_distributions (tenant_id, provider_tenant_id);
CREATE INDEX IF NOT EXISTS idx_msp_help_distributions_page
    ON msp_help_distributions (tenant_id, page_key) WHERE status IN ('active', 'unbound');