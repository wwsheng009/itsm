-- 跨租户单据流转 P2-①（模板分发 copy-in，2026-10-09）：
-- workflow_template_distributions 记录 provider → 客户租户的模板分发来源（每次分发一行，历史可追溯）。
-- owner 方向 = 客户租户（tenant_id，供租户守卫/RLS 识别）；provider_tenant_id 为来源。
-- 语义见 docs/multi-tenant/plan/msp-cross-tenant-record-flow-architecture.md §7.2（XFD5/D5=A、D6=A）。
CREATE TABLE IF NOT EXISTS workflow_template_distributions (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id                 INTEGER     NOT NULL,
    provider_tenant_id        INTEGER     NOT NULL,
    source_template_key       TEXT        NOT NULL,
    source_version            TEXT        NOT NULL,
    customer_template_key     TEXT        NOT NULL,
    customer_template_version TEXT        NOT NULL,
    distributed_by            INTEGER     NOT NULL,
    distributed_at            TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_wtd_customer_provider_key
    ON workflow_template_distributions (tenant_id, provider_tenant_id, source_template_key);

CREATE UNIQUE INDEX IF NOT EXISTS idx_wtd_customer_provider_key_version
    ON workflow_template_distributions (tenant_id, provider_tenant_id, source_template_key, customer_template_version);
