-- 20261030 问题调查域缺表补齐（problem investigations）
--
-- 背景：service/problem_investigation_repository.go 以原生 SQL 直读/直写 4 张表
--   （problem_investigations / problem_investigation_steps /
--     problem_root_cause_analyses / problem_solutions），
--   但历史迁移从未交付对应 DDL。demo 库 itsm_demo 缺表导致：
--   POST /api/v1/problem-investigation/investigations →
--   500（pq: relation "problem_investigations" does not exist, 42P01）；
--   GET  /problems/:id/summary 因逐子查询吞错而“看似正常”。
--
-- 幂等：全部 DDL 带 IF NOT EXISTS + 前置依赖判断，可重复执行（与
--   20261016_personal_access_tokens.sql 同范式）。
-- 回滚：同目录 20261030_problem_investigation_tables_down.sql。
-- 类型对齐：problems/users 的 id 均为 bigint GENERATED BY DEFAULT AS IDENTITY，
--   时间列与 problems.created_at 同型（timestamp with time zone）。
-- 说明：4 张表刻意不纳入 ent schema（见 repository 顶部注释），本文件为唯一 DDL 源；
--   tenant 隔离由 repository 的 JOIN problems/tenant_id 保证，故不建 RLS 策略。
DO $$
BEGIN
  IF to_regclass('public.problems') IS NULL OR to_regclass('public.users') IS NULL THEN
    RAISE NOTICE 'skip 20261030: problems/users not found';
    RETURN;
  END IF;

  -- 调查主表：每个 problem 至多一条（repository 以“存在即拒绝重复创建”为约束语义）
  CREATE TABLE IF NOT EXISTS problem_investigations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
      investigator_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
      status VARCHAR(32) NOT NULL DEFAULT 'in_progress',
      start_date TIMESTAMPTZ NOT NULL DEFAULT now(),
      estimated_completion_date TIMESTAMPTZ,
      actual_completion_date TIMESTAMPTZ,
      investigation_summary TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE UNIQUE INDEX IF NOT EXISTS ux_problem_investigations_problem
      ON problem_investigations (problem_id);

  -- 调查步骤
  CREATE TABLE IF NOT EXISTS problem_investigation_steps (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      investigation_id BIGINT NOT NULL REFERENCES problem_investigations(id) ON DELETE CASCADE,
      step_number INTEGER NOT NULL,
      step_title VARCHAR(255) NOT NULL,
      step_description TEXT,
      status VARCHAR(32) NOT NULL DEFAULT 'pending',
      assigned_to BIGINT REFERENCES users(id) ON DELETE SET NULL,
      start_date TIMESTAMPTZ,
      completion_date TIMESTAMPTZ,
      notes TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_problem_investigation_steps_investigation
      ON problem_investigation_steps (investigation_id, step_number);

  -- 根因分析
  CREATE TABLE IF NOT EXISTS problem_root_cause_analyses (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
      analyst_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
      analysis_method VARCHAR(32) NOT NULL,
      root_cause_description TEXT NOT NULL,
      contributing_factors TEXT,
      evidence TEXT,
      confidence_level DOUBLE PRECISION,
      analysis_date TIMESTAMPTZ NOT NULL DEFAULT now(),
      reviewed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      review_date TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_problem_root_cause_analyses_problem
      ON problem_root_cause_analyses (problem_id);

  -- 解决方案
  CREATE TABLE IF NOT EXISTS problem_solutions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      problem_id BIGINT NOT NULL REFERENCES problems(id) ON DELETE CASCADE,
      solution_type VARCHAR(32) NOT NULL,
      solution_description TEXT NOT NULL,
      proposed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      proposed_date TIMESTAMPTZ NOT NULL DEFAULT now(),
      status VARCHAR(32) NOT NULL DEFAULT 'proposed',
      priority VARCHAR(16) NOT NULL DEFAULT 'medium',
      estimated_effort_hours INTEGER,
      estimated_cost DOUBLE PRECISION,
      risk_assessment TEXT,
      approval_status VARCHAR(16) NOT NULL DEFAULT 'pending',
      approved_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      approval_date TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
  );
  CREATE INDEX IF NOT EXISTS idx_problem_solutions_problem
      ON problem_solutions (problem_id, created_at);

  RAISE NOTICE '20261030: problem investigation tables ensured';
END $$;
